def _stage(path: Path, scene_id: str) -> mujoco.MjModel:
    """The robot on one registered scene's ground, under that scene's lights.

    The ground geom is named `terrain`, which is the name `scenes/registry.py`
    binds a scene material to. Anything else compiles and then shows the
    untextured plane.
    """
    import scenes

    spec = mujoco.MjSpec.from_file(str(_SCENE_XML))
    ground = spec.worldbody.add_body()
    ground.name = "terrain"
    floor = ground.add_geom()
    floor.name = "terrain"
    floor.type = mujoco.mjtGeom.mjGEOM_PLANE
    floor.size = [0.0, 0.0, 0.01]
    robot = mujoco.MjSpec.from_file(str(path))
    spec.attach(robot, prefix="", frame=spec.worldbody.add_frame())
    scene = scenes.load(scene_id)
    for texture in scene.textures:
        texture.edit_spec(spec)
    for material in scene.materials:
        material.edit_spec(spec)
    for light in scene.lights:
        light.edit_spec(spec)
    if scene.headlight is not None:
        spec.visual.headlight.ambient = list(scene.headlight.ambient)
        spec.visual.headlight.diffuse = list(scene.headlight.diffuse)
        spec.visual.headlight.specular = list(scene.headlight.specular)
    return spec.compile()


def _home(model: mujoco.MjModel) -> mujoco.MjData:
    from tasks.jumper.common.constants import HOME, STAND_Z

    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    data.qpos[0:3] = (0.0, 0.0, STAND_Z)
    data.qpos[3:7] = (1.0, 0.0, 0.0, 0.0)
    for name, value in HOME.items():
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name)
        if jid < 0:
            jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, f"robot/{name}")
        if jid < 0:
            raise SystemExit(f"error: {name} is not in the model")
        data.qpos[int(model.jnt_qposadr[jid])] = value
    mujoco.mj_forward(model, data)
    return data


def _shell_lookat(model: mujoco.MjModel, data: mujoco.MjData) -> tuple[float, float, float]:
    gid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, "upper_shell_link_visual")
    if gid < 0:
        gid = mujoco.mj_name2id(
            model, mujoco.mjtObj.mjOBJ_GEOM, "robot/upper_shell_link_visual")
    if gid < 0:
        raise SystemExit("error: upper_shell_link_visual is not in the preview")
    pos = data.geom_xpos[gid]
    return (float(pos[0]), float(pos[1]), float(pos[2]))


class _Camera:
    """One off-screen camera. Collision hulls stay off, as in the live viewer."""

    def __init__(self, model: mujoco.MjModel, data: mujoco.MjData, size: tuple[int, int]):
        self.model = model
        self.data = data
        width, height = size
        model.vis.global_.offwidth = max(int(model.vis.global_.offwidth), width)
        model.vis.global_.offheight = max(int(model.vis.global_.offheight), height)
        self.renderer = mujoco.Renderer(model, height=height, width=width)
        self.option = mujoco.MjvOption()
        self.option.geomgroup[1] = 0
        self.cam = mujoco.MjvCamera()
        self.cam.type = mujoco.mjtCamera.mjCAMERA_FREE
        self.cam.lookat[:] = (0.0, 0.0, 0.07)

    def shoot(
        self, azimuth: float, elevation: float, distance: float,
        lookat: tuple[float, float, float] | None = None,
    ) -> np.ndarray:
        self.cam.azimuth = azimuth
        self.cam.elevation = elevation
        self.cam.distance = distance
        if lookat is not None:
            self.cam.lookat[:] = lookat
        self.renderer.update_scene(self.data, camera=self.cam, scene_option=self.option)
        return self.renderer.render().copy()

    def close(self) -> None:
        self.renderer.close()


def _shrink(frame: np.ndarray, size: tuple[int, int]) -> np.ndarray:
    return np.asarray(Image.fromarray(frame).resize(size, Image.Resampling.LANCZOS))


def _pair(left: np.ndarray, right: np.ndarray, left_name: str, right_name: str) -> Image.Image:
    gap = 8
    height, width = left.shape[:2]
    canvas = np.full((height, width * 2 + gap, 3), 236, np.uint8)
    canvas[:, :width] = left
    canvas[:, width + gap:] = right
    image = Image.fromarray(canvas)
    bar = 32
    out = Image.new("RGB", (image.width, image.height + bar), (244, 242, 236))
    out.paste(image, (0, 0))
    draw = ImageDraw.Draw(out)
    font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 18)
    for text, center in ((left_name, width // 2), (right_name, width + gap + width // 2)):
        box = draw.textbbox((0, 0), text, font=font)
        tw = box[2] - box[0]
        draw.text((center - tw / 2, image.height + 6), text, fill=(42, 36, 30), font=font)
    return out


def _mp4(frames: list[np.ndarray], path: Path, fps: int, size: tuple[int, int]) -> None:
    import imageio_ffmpeg

    writer = imageio_ffmpeg.write_frames(
        str(path), size=size, fps=fps, macro_block_size=1, codec="libx264",
        pix_fmt_out="yuv420p", output_params=["-crf", "23", "-movflags", "+faststart"],
    )
    writer.send(None)
    try:
        for frame in frames:
            writer.send(np.ascontiguousarray(frame).tobytes())
    finally:
        writer.close()


def _preview_name(kind: str, scene_id: str) -> str:
    """`crab-front` on the default scene, `crab-beach-front` on the beach."""
    if scene_id == "default":
        return f"crab-{kind}"
    return f"crab-{scene_id}-{kind}"


def render_preview(out_dir: Path = PREVIEW_DIR) -> None:
    """HOME-pose stills, default beside crab, on the default scene and the beach."""
    show = (440, 330)
    draw = (show[0] * 2, show[1] * 2)
    views = (
        ("front", 180.0, -14.0, 0.58),
        ("side", 90.0, -8.0, 0.62),
        ("three-quarter", 142.0, -18.0, 0.60),
    )
    # The shell is broad in YZ and thin along X, so "above" is a high angle on
    # that face and "side" is an oblique flank. Lookat is the carapace.
    closes = (
        ("close-above", 32.0, -52.0, 0.24),
        ("close-side", 78.0, -16.0, 0.26),
    )
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in ("crab-close.png", "crab-beach-close.png"):
        (out_dir / stale).unlink(missing_ok=True)
    for scene_id in PREVIEW_SCENES:
        cameras = {
            name: _Camera(_stage(path, scene_id), None, draw)
            for name, path in (("default", SRC), ("crab", DST))
        }
        try:
            for cam in cameras.values():
                cam.data = _home(cam.model)
            for kind, azimuth, elevation, distance in views:
                pair = _pair(
                    _shrink(cameras["default"].shoot(azimuth, elevation, distance), show),
                    _shrink(cameras["crab"].shoot(azimuth, elevation, distance), show),
                    "default",
                    "crab",
                )
                path = out_dir / f"{_preview_name(kind, scene_id)}.png"
                pair.save(path, optimize=True)
                print(f"[skin] {path.relative_to(REPO)}  {path.stat().st_size / 1e3:.0f} KB")

            look = _shell_lookat(cameras["crab"].model, cameras["crab"].data)
            close_show = (640, 480)
            for kind, azimuth, elevation, distance in closes:
                shell = _shrink(
                    cameras["crab"].shoot(azimuth, elevation, distance, lookat=look),
                    close_show,
                )
                close_path = out_dir / f"{_preview_name(kind, scene_id)}.png"
                Image.fromarray(shell).save(close_path, optimize=True)
                print(
                    f"[skin] {close_path.relative_to(REPO)}  "
                    f"{close_path.stat().st_size / 1e3:.0f} KB"
                )

            fps = 24
            seconds = 4
            turn_show = (480, 360)
            frames = []
            n = fps * seconds
            crab = cameras["crab"]
            for i in range(n):
                frames.append(
                    _shrink(crab.shoot(180.0 + 360.0 * i / n, -16.0, 0.64), turn_show)
                )
            video = out_dir / f"{_preview_name('turntable', scene_id)}.mp4"
            _mp4(frames, video, fps, turn_show)
            print(f"[skin] {video.relative_to(REPO)}  {video.stat().st_size / 1e6:.2f} MB")
        finally:
            for cam in cameras.values():
                cam.close()


def _gl_failure(exc: BaseException) -> bool:
    text = f"{type(exc).__name__}: {exc}".lower()
    return any(tok in text for tok in ("egl", "osmesa", "gl", "glfw", "display", "glad"))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--preview", action="store_true",
                    help="HOME stills and a turntable, on the default scene and the beach")
    ap.add_argument("--preview-dir", type=Path, default=PREVIEW_DIR)
    args = ap.parse_args(argv)

    write_skin()
    print(f"[skin] {DST.relative_to(REPO)}")
    print(f"[skin] textures in {TEXTURE_DIR.relative_to(REPO)}")
    if not args.preview:
        return 0
    try:
        render_preview(args.preview_dir)
    except Exception as exc:
        if os.environ.get("MUJOCO_GL") != "osmesa" and _gl_failure(exc):
            print(f"[skin] {os.environ.get('MUJOCO_GL')} failed ({exc}); retrying with osmesa")
            os.environ["MUJOCO_GL"] = "osmesa"
            os.execv(sys.executable, [sys.executable, *sys.argv])
        raise
    return 0


