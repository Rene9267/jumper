def appearance(body: str) -> str:
    """Which material a link wears, or ``sensor`` to leave it black.

    Groups, matched on the link name:

    * shell — the upper shell, ivory with crimson spots. The chassis
      (`base_link`) is the plain ivory underside.
    * leg — calves and foot tips, ivory with a few reddish dots.
    * leg joint — hips and thighs, the same dotted ivory.
    * claw — the two front chelipeds, except their tips, dotted ivory.
      Forearms, pads and grip inserts stay plain ivory.
    * tip — `finger` and `finger_tip`, darker red-brown.
    * sensor — display, camera, ToF.
    """
    if body in SENSORS:
        return "sensor"
    if "finger_tip" in body or body.endswith("_finger_link"):
        return "tip"
    if body.startswith(("LF_", "RF_")):
        if any(tok in body for tok in ("pad", "grip_insert", "forearm")):
            return "claw_joint"
        return "claw"
    if body == "base_link":
        return "underside"
    if body == "upper_shell_link":
        return "shell"
    if body.startswith(("LM_", "RM_", "LR_", "RR_")):
        if "hip" in body or "thigh" in body:
            return "leg_joint"
        return "leg"
    raise KeyError(f"no crab role for link {body!r}")


