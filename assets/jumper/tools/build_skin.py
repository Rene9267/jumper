def _save_textures(images: dict[str, np.ndarray], texture_dir: Path) -> None:
    texture_dir.mkdir(parents=True, exist_ok=True)
    # The previous skin was six cube faces per picture. A re-run must not leave
    # them beside the tile, where a reader would take the stale file for the map.
    for name in images:
        for face in _CUBE_FACES:
            (texture_dir / f"{name}_{face}.png").unlink(missing_ok=True)
    for name, image in images.items():
        Image.fromarray(image, mode="RGB").save(texture_dir / f"{name}.png")


def _save_meshes(meshes: dict[str, bytes], skin_dir: Path) -> None:
    skin_dir.mkdir(parents=True, exist_ok=True)
    keep = set(meshes)
    for stale in skin_dir.glob("*.obj"):
        if stale.name not in keep:
            stale.unlink()
    for name, payload in meshes.items():
        (skin_dir / name).write_bytes(payload)


def _paint(spec: mujoco.MjSpec, images: dict[str, np.ndarray]) -> None:
    collision = _collision_mesh_names(spec)
    for name in _textured_mesh_names(spec):
        path = str((SKIN_DIR / f"{name}.obj").resolve())
        if name in collision:
            skin_mesh = spec.add_mesh()
            skin_mesh.name = f"{name}_skin"
            skin_mesh.file = path
            for body in spec.bodies:
                for geom in body.geoms:
                    if geom.name.endswith("_visual") and geom.meshname == name:
                        geom.meshname = skin_mesh.name
        else:
            spec.mesh(name).file = path

    for name in images:
        tex = spec.add_texture()
        tex.name = name
        tex.type = mujoco.mjtTexture.mjTEXTURE_2D
        tex.builtin = mujoco.mjtBuiltin.mjBUILTIN_NONE
        tex.nchannel = 3
        # Absolute while the file is open: to_xml reads the pixels. _xml_text
        # writes the path back relative to the XML.
        tex.file = str((TEXTURE_DIR / f"{name}.png").resolve())
        # AUTO is written back as linear, and a linear reading of an sRGB PNG
        # comes out dark and dull. The files are sRGB.
        tex.colorspace = mujoco.mjtColorSpace.mjCOLORSPACE_SRGB

    rgba_of = {
        role: flat_rgba(images[finish.texture], finish.tint)
        for role, finish in MATERIALS.items()
    }
    for role, finish in MATERIALS.items():
        mat = spec.add_material(
            name=f"crab_{role}",
            rgba=[*finish.tint, 1.0],
            texuniform=False,
            texrepeat=[1.0, 1.0],
            specular=finish.specular,
            shininess=finish.shininess,
            reflectance=0.0,
        )
        mat.roughness = finish.roughness
        mat.metallic = 0.0
        mat.textures[int(mujoco.mjtTextureRole.mjTEXROLE_RGB)] = finish.texture

    spec.modelname = "jumper_crab"
    for body in spec.bodies:
        if body.name in ("", "world"):
            continue
        role = appearance(body.name)
        for geom in body.geoms:
            if role == "sensor":
                continue
            if geom.name.endswith("_visual"):
                geom.material = f"crab_{role}"
                # White, times a near-white tint. A dark rgba here multiplies the
                # picture and the marble disappears.
                geom.rgba[:] = [*MATERIALS[role].tint, 1.0]
            elif geom.name.endswith("_meshcol"):
                geom.material = ""
                geom.rgba[:] = rgba_of[role]
            else:
                raise RuntimeError(f"unexpected geom {geom.name!r} on {body.name}")


def _xml_text(spec: mujoco.MjSpec) -> str:
    xml = HEADER + spec.to_xml()
    xml = re.sub(
        r'file="[^"]*/((?:skin/[^"]+\.obj|textures/(?:carapace|ventral|tip)\.png))"',
        r'file="\1"',
        xml,
    )
    xml = re.sub(
        r'(<texture\b[^>]*colorspace=")linear(" name="(?:carapace|ventral|tip)")',
        r"\1sRGB\2",
        xml,
    )
    # Built by concatenation so the source does not itself contain a machine path.
    # tests/test_layout.py flags a quoted /home or /Users path.
    absolute = tuple("/" + part for part in ("tmp/", "home/", "Users/", "workspace/"))
    if any(token in xml for token in absolute):
        raise RuntimeError("the skin XML still contains an absolute texture path")
    return xml


def physics_snapshot(model: mujoco.MjModel) -> dict[str, np.ndarray]:
    return {name: np.array(getattr(model, name)) for name in PHYSICS_FIELDS}


def geom_size_error(src: mujoco.MjModel, dst: mujoco.MjModel) -> str | None:
    """None when sizes match. Collision exact; visual within a float32 ulp."""
    if src.ngeom != dst.ngeom:
        return f"geom count {src.ngeom} vs {dst.ngeom}"
    for i in range(src.ngeom):
        name = mujoco.mj_id2name(src, mujoco.mjtObj.mjOBJ_GEOM, i) or str(i)
        a = np.asarray(src.geom_size[i])
        b = np.asarray(dst.geom_size[i])
        if name.endswith("_visual"):
            if not np.allclose(a, b, rtol=0.0, atol=VISUAL_GEOM_SIZE_ATOL):
                return f"{name} visual size moved by more than a ulp ({a} vs {b})"
        elif not np.array_equal(a, b):
            return f"{name} size changed ({a} vs {b})"
    return None


def assert_physics_equal(src: Path, dst: Path) -> None:
    """Compile both files and require the dynamics arrays to be identical."""
    base = mujoco.MjModel.from_xml_path(str(src))
    other = mujoco.MjModel.from_xml_path(str(dst))
    for name in PHYSICS_FIELDS:
        a = np.asarray(getattr(base, name))
        b = np.asarray(getattr(other, name))
        if a.shape != b.shape or not np.array_equal(a, b):
            raise SystemExit(
                f"error: {dst.name} changed {name} "
                f"({a.shape} vs {b.shape}); the skin must not move the dynamics"
            )
    size_err = geom_size_error(base, other)
    if size_err is not None:
        raise SystemExit(f"error: {dst.name} changed geom_size: {size_err}")


def write_skin(
    dst: Path = DST, texture_dir: Path = TEXTURE_DIR, src: Path = SRC,
    skin_dir: Path = SKIN_DIR,
) -> None:
    """Write the textures, the box-mapped meshes and `jumper_crab.xml`.

    Leave `src` unread-only. Paths are the ones beside `jumper_crab.xml`; the
    XML names them relative to itself.
    """
    if not src.is_file():
        raise SystemExit(f"error: {src} is not there. The skin is generated from it.")
    if texture_dir.resolve() != (dst.parent / "textures").resolve():
        raise SystemExit(
            f"error: write textures to {dst.parent / 'textures'}, beside the XML"
        )
    if skin_dir.resolve() != (dst.parent / "skin").resolve():
        raise SystemExit(f"error: write meshes to {dst.parent / 'skin'}, beside the XML")
    before = src.read_bytes()
    images = {name: fn() for name, fn in TEXTURES.items()}
    meshes = baked_meshes(src)
    _save_textures(images, texture_dir)
    _save_meshes(meshes, skin_dir)
    spec = mujoco.MjSpec.from_file(str(src))
    _paint(spec, images)
    text = _xml_text(spec)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_suffix(dst.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    try:
        assert_physics_equal(src, tmp)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise
    tmp.replace(dst)
    if src.read_bytes() != before:
        raise SystemExit(f"error: {src.name} changed while the skin was written")
    cap = images["carapace"].reshape(-1, 3)
    lum = cap.mean(axis=1)
    dark = float(cap[lum <= np.median(lum)].mean())
    print(f"[skin] carapace dark-half sRGB {dark:.1f}  ventral mean {images['ventral'].mean():.1f}")


