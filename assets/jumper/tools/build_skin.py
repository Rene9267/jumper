#!/usr/bin/env python3
"""Paint a Mediterranean shore-crab skin onto a copy of jumper.xml.

The default model stays as `build_jumper.py` wrote it. This script loads that
file through MjSpec, writes `assets/jumper/jumper_crab.xml`, and saves the
textures under `assets/jumper/textures/` plus box-mapped visual meshes under
`assets/jumper/skin/`. Collision geometry, contact, mass, inertia, joints and
actuators are not edited. The script compiles both models and refuses to keep
an XML whose dynamics differ.

    python assets/jumper/tools/build_skin.py
    python assets/jumper/tools/build_skin.py --preview

The colours follow *Pachygrapsus marmoratus* and *Carcinus aestuarii*: a mid
olive-brown carapace with a fine network of dark olive-purple veins and small
pale flecks, a pale cream-ochre underside, thighs and forearms, and dark
brown-black claw tips. The display, the camera and the ToF stay black.

The visual STLs have no texture coordinates. A 2D texture on them is one texel,
and a cube map stretched across the domed shell converges on a point. Each
painted visual mesh is therefore rewritten as an OBJ whose texcoords are an
orthographic box projection (the two axes perpendicular to the triangle), at
`UV_PER_METRE` cycles, and the material samples that picture with `texuniform`
off. The pictures are tileable, so a face edge meets itself. NumPy and Pillow
only, seed `SEED`.

The geom colour multiplies the texture. Visual geoms stay a near-white tint and
the picture carries the colour. `reflectance` is 0: a mirror of a dark sky pulls
the shell toward black. `*_meshcol` geoms take the flat average rgba and no
material, so `--strip-visual` stays crab-coloured.

Rewriting a visual mesh stores its vertices as float32, and `geom_size` is that
box rounded back to float64, so a visual size can move by a few ulps. Collision
meshes are still the original STLs. Mass, inertia, friction and joints are
compared exactly.

`--preview` draws the HOME pose off-screen under `scenes/default.py` and
`scenes/beach.py`: front, side, three-quarter, the shell from above and from
the side, and a short turntable. `MUJOCO_GL=egl`, and osmesa if that context
cannot be created.
"""

