def _save_textures(texture_dir: Path, size: int = SIZE) -> dict[str, np.ndarray]:
    texture_dir.mkdir(parents=True, exist_ok=True)
    images = {}
    for name, fn in TEXTURES.items():
        image = fn(size)
        Image.fromarray(image, mode="RGB").save(texture_dir / f"{name}.png")
        images[name] = image
    return images


def _paint(spec: mujoco.MjSpec, images: dict[str, np.ndarray], texture_dir: Path) -> None:
    for name, image in images.items():
        tex = spec.add_texture(
            name=name,
            type=mujoco.mjtTexture.mjTEXTURE_2D,
            builtin=mujoco.mjtBuiltin.mjBUILTIN_NONE,
            file=str((texture_dir / f"{name}.png").resolve()),
            width=int(image.shape[1]),
            height=int(image.shape[0]),
            nchannel=3,
        )
        # AUTO is written back as linear, and a linear reading of an sRGB PNG
        # comes out dark and dull. The files are sRGB.
        tex.colorspace = mujoco.mjtColorSpace.mjCOLORSPACE_SRGB

    rgba_of = {
        role: flat_rgba(images[finish.texture], finish.tint)
        for role, finish in MATERIALS.items()
    }
    for role, finish in MATERIALS.items():
        mat = spec.add_material(
            name=f"crab_{role}",
            rgba=[*finish.tint, 1.0],
            texuniform=False,
            texrepeat=list(finish.texrepeat),
            specular=finish.specular,
            shininess=finish.shininess,
            reflectance=finish.reflectance,
        )
        mat.roughness = finish.roughness
        mat.metallic = 0.0
        mat.textures[int(mujoco.mjtTextureRole.mjTEXROLE_RGB)] = finish.texture

    spec.modelname = "jumper_crab"
    for body in spec.bodies:
        if body.name in ("", "world"):
            continue
        role = appearance(body.name)
        for geom in body.geoms:
            if role == "sensor":
                continue
            if geom.name.endswith("_visual"):
                geom.material = f"crab_{role}"
                geom.rgba[:] = rgba_of[role]
            elif geom.name.endswith("_meshcol"):
                geom.material = ""
                geom.rgba[:] = rgba_of[role]
            else:
                raise RuntimeError(f"unexpected geom {geom.name!r} on {body.name}")


def _xml_text(spec: mujoco.MjSpec) -> str:
    xml = HEADER + spec.to_xml()
    xml = re.sub(
        r'file="(?:[^"]*/)?(carapace|ventral|tip)\.png"',
        r'file="textures/\1.png"',
        xml,
    )
    xml = re.sub(
        r'(<texture\b[^>]*colorspace=")linear(" name="(?:carapace|ventral|tip)")',
        r"\1sRGB\2",
        xml,
    )
    # Built by concatenation so the source does not itself contain a machine path.
    # tests/test_layout.py flags a quoted /home or /Users path.
    absolute = tuple("/" + part for part in ("tmp/", "home/", "Users/", "workspace/"))
    if any(token in xml for token in absolute):
        raise RuntimeError("the skin XML still contains an absolute texture path")
    return xml


def physics_snapshot(model: mujoco.MjModel) -> dict[str, np.ndarray]:
    return {name: np.array(getattr(model, name)) for name in PHYSICS_FIELDS}


def assert_physics_equal(src: Path, dst: Path) -> None:
    """Compile both files and require the dynamics arrays to be identical."""
    base = mujoco.MjModel.from_xml_path(str(src))
    other = mujoco.MjModel.from_xml_path(str(dst))
    for name in PHYSICS_FIELDS:
        a = np.asarray(getattr(base, name))
        b = np.asarray(getattr(other, name))
        if a.shape != b.shape or not np.array_equal(a, b):
            raise SystemExit(
                f"error: {dst.name} changed {name} "
                f"({a.shape} vs {b.shape}); the skin must not move the dynamics"
            )


def write_skin(
    dst: Path = DST, texture_dir: Path = TEXTURE_DIR, src: Path = SRC, size: int = SIZE,
) -> None:
    """Write the textures and `jumper_crab.xml`. Leave `src` unread-only."""
    if not src.is_file():
        raise SystemExit(f"error: {src} is not there. The skin is generated from it.")
    # The XML names meshes and textures relative to its own directory.
    if texture_dir.resolve() != (dst.parent / "textures").resolve():
        raise SystemExit(
            f"error: write textures to {dst.parent / 'textures'}, beside the XML"
        )
    before = src.read_bytes()
    images = _save_textures(texture_dir, size)
    spec = mujoco.MjSpec.from_file(str(src))
    _paint(spec, images, texture_dir)
    text = _xml_text(spec)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_suffix(dst.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    try:
        assert_physics_equal(src, tmp)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise
    tmp.replace(dst)
    if src.read_bytes() != before:
        raise SystemExit(f"error: {src.name} changed while the skin was written")


