#!/usr/bin/env python3
"""Paint a Mediterranean shore-crab skin onto a copy of jumper.xml.

The default model stays as `build_jumper.py` wrote it. This script loads that
file through MjSpec, writes `assets/jumper/jumper_crab.xml`, and saves the
textures under `assets/jumper/textures/`. Collision geometry, contact, mass,
inertia, joints and actuators are not edited; the script compiles both models
and refuses to keep an XML whose dynamics differ.

    python assets/jumper/tools/build_skin.py
    python assets/jumper/tools/build_skin.py --preview

The colours are *Calappa granulata*, the Mediterranean box crab: a light
cream-ivory carapace with a warm peach tint, crisp crimson to burgundy spots,
cream legs with a few small reddish dots, and darker red-brown claw tips. The
display, the camera and the ToF stay black, which is what keeps the machine
recognisable. `IVORY`, `PEACH`, `SPOT_CRIMSON` and `SPOT_BURGUNDY` at the top
of this file are the swatches.

The visual STLs have no texture coordinates. `texuniform` paints a 2D picture
from the mesh's stored X and Y, and on this shell those axes are the thin
direction and one long direction, so a tile becomes lengthwise streaks. A
dorsal-only projection keeps a disc round on the crown and stretches it into
a vertical slit on the steep flanks, which is about half the shell. The shell
therefore carries box texcoords: each face is projected on the plane it faces,
and a vertex on the ridge between two planes keeps a coordinate for each. The
carapace picture is an atlas of those projections, so the discs stay discs
from above and from the side. Spots are larger toward the front rim and the
outline, sparse on the crown. Legs use a small `texrepeat`. The pictures are
NumPy and Pillow only, seed `SEED`. No second mesh file is committed. The
shell's collision geom is untouched, so the silhouette matches the default
model.

The geom colour multiplies the texture. Leaving the factory red, or writing the
texture's own dark average into `rgba`, crushes the shell toward black and
pushes a warm belly texel toward orange. Visual geoms are therefore a near-white
tint, and the picture carries the colour. `*_meshcol` geoms take the matching
flat rgba and no material, so a camera that has had the visual meshes stripped
is still crab-coloured, and a material cannot override that rgba.

`--preview` draws the HOME pose off-screen under `scenes/default.py` and
`scenes/beach.py`: front, side, three-quarter, the shell from above and from
the side, and a short turntable. `MUJOCO_GL=egl`, and osmesa if that context
cannot be created.
"""

