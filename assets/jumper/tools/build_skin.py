def _rng(salt: int) -> np.random.Generator:
    return np.random.default_rng(SEED + salt)


def _smooth(t: np.ndarray) -> np.ndarray:
    return t * t * (3.0 - 2.0 * t)


def _value_noise(h: int, w: int, cells: int, rng: np.random.Generator) -> np.ndarray:
    """Seamless bilinear value noise. `cells` is the grid, tiled at the edges."""
    grid = rng.random((cells, cells))
    ys = np.linspace(0.0, cells, h, endpoint=False)
    xs = np.linspace(0.0, cells, w, endpoint=False)
    y0 = np.floor(ys).astype(np.int32)
    x0 = np.floor(xs).astype(np.int32)
    fy = _smooth(ys - y0)[:, None]
    fx = _smooth(xs - x0)[None, :]
    y0 %= cells
    x0 %= cells
    y1 = (y0 + 1) % cells
    x1 = (x0 + 1) % cells
    g00 = grid[y0][:, x0]
    g01 = grid[y0][:, x1]
    g10 = grid[y1][:, x0]
    g11 = grid[y1][:, x1]
    return (g00 * (1.0 - fx) + g01 * fx) * (1.0 - fy) + (g10 * (1.0 - fx) + g11 * fx) * fy


def _fbm(
    h: int, w: int, rng: np.random.Generator, octaves: int = 5, base: int = 2,
    persistence: float = 0.5,
) -> np.ndarray:
    acc = np.zeros((h, w), np.float64)
    amp = 1.0
    total = 0.0
    for i in range(octaves):
        acc += amp * _value_noise(h, w, base * 2**i, rng)
        total += amp
        amp *= persistence
    return acc / total


def _lerp(a: np.ndarray, b: np.ndarray, t: np.ndarray) -> np.ndarray:
    tt = t[..., None]
    return a * (1.0 - tt) + b * tt


def _u8(color: np.ndarray) -> np.ndarray:
    return np.clip(np.rint(np.clip(color, 0.0, 1.0) * 255.0), 0, 255).astype(np.uint8)


def _span(v: np.ndarray) -> np.ndarray:
    """Spread a field that has collapsed toward 0.5 out across ``[0, 1]``.

    The percentiles are one affine map of a tileable field, so the tile survives.
    They are part of the seed: same noise, same stretch.
    """
    lo, hi = np.percentile(v, (2.0, 98.0))
    return np.clip((v - lo) / (hi - lo + 1e-8), 0.0, 1.0)


def _rgb(r: float, g: float, b: float) -> np.ndarray:
    """sRGB bytes as a linear mix weight. The PNG stores sRGB; MuJoCo is told so."""
    return np.array([r, g, b]) / 255.0


def _ridge(field: np.ndarray, width: float) -> np.ndarray:
    """1 on the midline of a tileable field, 0 outside a thin band."""
    return np.clip((width - np.abs(field - 0.5)) / width, 0.0, 1.0)


def _carapace(size: int = SIZE) -> np.ndarray:
    """Mid olive-brown with thin dark olive-purple veins and small pale flecks.

    The low octaves are a network of lines, not blocks of colour. At
    `UV_PER_METRE` a base cell is about 1.4 cm on the shell and a vein is about
    2 mm, which is the marbling of *Pachygrapsus marmoratus* rather than a
    camouflage blotch. The dark half of the picture is meant to sit near sRGB
    90–120: lower than that, and the default headlight renders it as black.
    """
    h = w = size
    rng = _rng(100)
    coarse = _span(_fbm(h, w, rng, octaves=5, base=6, persistence=0.55))
    fine = _span(_fbm(h, w, rng, octaves=4, base=12, persistence=0.5))
    grain = _value_noise(h, w, 48, rng)
    speck = _value_noise(h, w, 40, rng)
    vein = np.maximum(_ridge(coarse, 0.05), _ridge(fine, 0.028) * 0.85)
    fleck = np.clip((speck - 0.86) / 0.08, 0.0, 1.0)

    olive = _rgb(136, 122, 84)
    olive_dim = _rgb(124, 110, 74)
    vein_c = _rgb(52, 34, 58)
    fleck_c = _rgb(210, 190, 146)
    color = _lerp(olive, olive_dim, grain * 0.4)
    color = _lerp(color, vein_c, vein)
    color = _lerp(color, fleck_c, fleck * (1.0 - vein))
    return _u8(color)


def _ventral(size: int = SIZE) -> np.ndarray:
    """Pale cream-ochre, a step darker than a white that the beach sun clips.

    The stains stay inside the cream. A saturated ochre reads as orange, and a
    mean up near 210 renders as white plastic under `scenes/beach.py`.
    """
    h = w = size
    rng = _rng(200)
    field = _span(_fbm(h, w, rng, octaves=4, base=4))
    stain = _span(_fbm(h, w, rng, octaves=3, base=3))
    grain = _value_noise(h, w, 36, rng)

    buff = _rgb(170, 156, 134)
    cream = _rgb(188, 174, 152)
    pale = _rgb(204, 190, 170)
    mark = _rgb(148, 132, 110)

    color = _lerp(buff, cream, field)
    color = _lerp(color, pale, np.clip((field - 0.55) * 2.2, 0.0, 1.0) * 0.55)
    color = _lerp(color, mark, np.clip((stain - 0.78) * 6.0, 0.0, 1.0) * 0.35)
    color *= (0.99 + 0.02 * grain)[..., None]
    return _u8(color)


def _tip(size: int = SIZE) -> np.ndarray:
    """Dark brown-black chitin, with a little grain so the tip is not plastic."""
    h = w = size
    rng = _rng(300)
    field = _span(_fbm(h, w, rng, octaves=4, base=5))
    grain = _value_noise(h, w, 64, rng)
    color = _lerp(_rgb(34, 18, 12), _rgb(78, 42, 24), field)
    color *= (0.86 + 0.28 * grain)[..., None]
    return _u8(color)


def carapace(size: int = SIZE) -> np.ndarray:
    return _carapace(size)


def ventral(size: int = SIZE) -> np.ndarray:
    return _ventral(size)


def tip(size: int = SIZE) -> np.ndarray:
    return _tip(size)


