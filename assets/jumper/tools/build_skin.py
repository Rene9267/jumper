def flat_rgba(image: np.ndarray, tint: tuple[float, float, float]) -> list[float]:
    """The colour a picture averages to, times the material tint.

    `--strip-visual` drops the meshes that carry the material, and the collision
    geom that remains has no texture. This rgba is that average, so the flat
    stand-in is the same colour the picture reads as.
    """
    mean = image.reshape(-1, 3).astype(np.float64).mean(axis=0) / 255.0
    rgb = np.clip(mean * np.asarray(tint, np.float64), 0.0, 1.0)
    return [float(rgb[0]), float(rgb[1]), float(rgb[2]), 1.0]


# ── Box UVs ───────────────────────────────────────────────────────────────


def _mesh_arrays(model: mujoco.MjModel, name: str) -> tuple[np.ndarray, np.ndarray]:
    mid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_MESH, name)
    if mid < 0:
        raise KeyError(name)
    vadr = int(model.mesh_vertadr[mid])
    nv = int(model.mesh_vertnum[mid])
    fadr = int(model.mesh_faceadr[mid])
    nf = int(model.mesh_facenum[mid])
    verts = np.asarray(model.mesh_vert[vadr:vadr + nv], dtype=np.float64)
    faces = np.asarray(model.mesh_face[fadr:fadr + nf], dtype=np.int64)
    return verts, faces


def box_uvs(verts: np.ndarray, faces: np.ndarray, scale: float) -> tuple[np.ndarray, np.ndarray]:
    """Orthographic box coordinates, one pair per (vertex, dominant axis).

    A triangle takes the two axes perpendicular to its face normal, so the
    sample does not slide toward a single point the way a cube map does on the
    dome. The same vertex keeps a separate coordinate on each side of an axis
    change. Welding those is what stretches the dome into a pinch.
    """
    tri = verts[faces]
    normal = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    axis = np.abs(normal).argmax(axis=1).astype(np.int64)
    corners = faces.reshape(-1).astype(np.int64)
    keys = corners * 3 + np.repeat(axis, 3)
    uniq, inv = np.unique(keys, return_inverse=True)
    vi = uniq // 3
    ax = uniq % 3
    pts = verts[vi]
    # axis 0 → (y, z), axis 1 → (x, z), axis 2 → (x, y)
    u = np.where(ax == 0, pts[:, 1], pts[:, 0])
    v = np.where(ax == 2, pts[:, 1], pts[:, 2])
    coords = np.column_stack((u, v)) * float(scale)
    return coords, inv.reshape(-1, 3)


def _obj_bytes(
    verts: np.ndarray, faces: np.ndarray, uvs: np.ndarray, ft: np.ndarray,
) -> bytes:
    lines = ["# Generated by assets/jumper/tools/build_skin.py. Box UVs; do not edit."]
    lines.extend(f"v {x:.8g} {y:.8g} {z:.8g}" for x, y, z in verts)
    lines.extend(f"vt {u:.8g} {v:.8g}" for u, v in uvs)
    f = faces + 1
    t = ft + 1
    lines.extend(
        f"f {a}/{ta} {b}/{tb} {c}/{tc}"
        for (a, b, c), (ta, tb, tc) in zip(f, t, strict=True)
    )
    return ("\n".join(lines) + "\n").encode("ascii")


def _textured_mesh_names(spec: mujoco.MjSpec) -> list[str]:
    names = []
    seen = set()
    for body in spec.bodies:
        if body.name in ("", "world") or appearance(body.name) == "sensor":
            continue
        for geom in body.geoms:
            if not geom.name.endswith("_visual"):
                continue
            if geom.meshname in seen:
                continue
            seen.add(geom.meshname)
            names.append(geom.meshname)
    return names


def _collision_mesh_names(spec: mujoco.MjSpec) -> set[str]:
    """Meshes a collision geom still has to reference.

    Six links have no `*_col` hull, so the visual mesh is the collider. Replacing
    that file would move `geom_size`. Those keep the STL, and the visual geom
    points at a copy that carries the texcoords.
    """
    names = set()
    for body in spec.bodies:
        for geom in body.geoms:
            if geom.name.endswith("_meshcol"):
                names.add(geom.meshname)
    return names


def baked_meshes(src: Path = SRC) -> dict[str, bytes]:
    """OBJ bytes for every painted visual mesh, keyed by file name."""
    model = mujoco.MjModel.from_xml_path(str(src))
    spec = mujoco.MjSpec.from_file(str(src))
    out = {}
    for name in _textured_mesh_names(spec):
        verts, faces = _mesh_arrays(model, name)
        uvs, ft = box_uvs(verts, faces, UV_PER_METRE)
        out[f"{name}.obj"] = _obj_bytes(verts, faces, uvs, ft)
    return out


