@dataclass(frozen=True)
class Finish:
    """One material, and the tint a visual geom multiplies the texture by.

    `tint` stays near white. The picture carries the colour; the tint only
    separates shell, leg and claw by a small hue shift. `reflectance` is 0:
    MuJoCo's reflection is a mirror of the whole scene, and on a dark sky it
    pulls the shell toward black.
    """

    texture: str
    tint: tuple[float, float, float]
    specular: float
    shininess: float
    roughness: float


MATERIALS: dict[str, Finish] = {
    "shell": Finish("carapace", (1.0, 1.0, 1.0), 0.12, 0.18, 0.62),
    "leg": Finish("carapace", (0.96, 1.0, 0.90), 0.10, 0.16, 0.68),
    "claw": Finish("carapace", (1.0, 0.96, 0.97), 0.14, 0.22, 0.55),
    "underside": Finish("ventral", (1.0, 1.0, 1.0), 0.03, 0.06, 0.92),
    "leg_joint": Finish("ventral", (0.98, 0.97, 0.95), 0.03, 0.06, 0.92),
    "claw_joint": Finish("ventral", (1.0, 0.98, 0.96), 0.035, 0.07, 0.90),
    "tip": Finish("tip", (1.0, 1.0, 1.0), 0.22, 0.34, 0.42),
}


def appearance(body: str) -> str:
    """Which material a link wears, or ``sensor`` to leave it black.

    Groups, matched on the link name:

    * shell — the upper shell. The chassis (`base_link`) is the underside.
    * leg — calves and foot tips of the four walking legs.
    * leg joint — hips and thighs, the pale cream of the belly.
    * claw — the two front chelipeds, except their tips. Forearms, pads and
      grip inserts are the same pale cream.
    * tip — `finger` and `finger_tip`, the dark dactyl ends.
    * sensor — display, camera, ToF.
    """
    if body in SENSORS:
        return "sensor"
    if "finger_tip" in body or body.endswith("_finger_link"):
        return "tip"
    if body.startswith(("LF_", "RF_")):
        if any(tok in body for tok in ("pad", "grip_insert", "forearm")):
            return "claw_joint"
        return "claw"
    if body == "base_link":
        return "underside"
    if body == "upper_shell_link":
        return "shell"
    if body.startswith(("LM_", "RM_", "LR_", "RR_")):
        if "hip" in body or "thigh" in body:
            return "leg_joint"
        return "leg"
    raise KeyError(f"no crab role for link {body!r}")


